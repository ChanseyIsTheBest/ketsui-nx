#!/usr/bin/env python3
"""Renut's renderer (app/src/renut_engine) for Ketsui's Direct3D: Futari's guest addresses replaced by Ketsui's
(ketsui-nx, 2026-10-27).

Ketsui links the same XDK as Futari (2.0.9328), so its D3DDevice is Futari's word for word: the renderer keeps
Futari's device offsets (tools/renut_futari_layout.py). guwange-nx's renderer (XDK 2.0.11164, one word inserted at
+0x359C) was not taken as it is: Ketsui's tree is futari-nx's renderer plus guwange-nx's generic changes (its own
hooks, the 16-bit texture paths, the bound fetch specialisation, the latency trace), without guwange-nx's layout step.
Only the guest addresses differ. Each was found by pairing Futari's Direct3D (0x82080000-0x820B0000) with Ketsui's by
instruction shape, then reading the lis + displacement (or bl) at the same instruction of both
(tools/ketsui_futari_pairs.py --addr ...), and its bytes compared where it is data:

  kGlobalQwordVa            0x821E1AF8 -> 0x82E0BA90  the device init's copy into +10880; bytes 0002 0000 2470 4000
                                                      (equal to Futari's)
  kVdGlobalDeviceImportSlot 0x820005F8 -> 0x82000798  17 accesses (the hardware init, BlockOnFence, IsFencePending,
                                                      Destroy); both slots hold FFCAE000
  kRenderStateTable         0x821E14F0 -> 0x82E0B478  InitializeApiState; the same layout (getter, setter, default),
  kSamplerStateTable        0x821E19B0 -> 0x82E0B938  0x4C0 apart in both; the defaults equal, the pointers Ketsui's
  kFormatTable (2 files)    0x82003430 -> 0x82149990  10 accesses; its 128 bytes equal Futari's
  kFullViewport             0x820031D0 -> 0x821497E4  D3D_SetSurfaceInfo; its 24 bytes equal Futari's
  kHiZOwnerVa               0x821ED330 -> 0x8300465C  CreateSurface / Destroy (4 accesses)
  kGameNoLargePagesVa       0x821ED308 -> 0x83004644  XPhysicalAlloc 82089ED8 -> 828D18B8
  kDeviceCapsVa             0x82003800 -> 0x82149E48  GetDeviceCaps' D3DCAPS9 (Ketsui links GetDeviceCaps 828EC3F8);
                                                      its 304 bytes equal Futari's
  kVblankHandler            0x820A4C08 -> 0x828DDB70  the handler, 69 instructions as Futari's; kVblankHandlerHash is
  kVblankHandlerHash        -> 0xBE1E3F741ED93A78     the FNV-1a of those 69 words in out/default_image.bin
  GuestGetCurrentThreadId   sub_8208DA10 -> sub_829F3C70  the device init's call (7 pairs)
  DefaultXMemFree           sub_82088CE0 -> sub_829F3C40  CreateDevice's failure path (27 pairs)
  OriginalSetFVF            sub_8225FB78 (Guwange) -> sub_828E63B8  guwange-nx's SetFVF hook runs the original first;
                                                      Ketsui's SetFVF is Guwange's instruction for instruction

  python tools/renut_ketsui_layout.py            dry run: every line it would change
  python tools/renut_ketsui_layout.py --write    apply (idempotent: a translated file carries a marker)
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENGINE = os.path.join(ROOT, 'app', 'src', 'renut_engine')
MARK = '// ketsui-nx: guest addresses translated to Ketsui\'s (tools/renut_ketsui_layout.py)'
SKIP_FILES = {'futari_renut_hooks.h', 'futari_renut_core_hooks.cpp'}  # generated by renut_ketsui_hooks.py

GLOBALS = {
    'kGlobalQwordVa': ('0x821E1AF8', '0x82E0BA90'),
    'kVdGlobalDeviceImportSlot': ('0x820005F8', '0x82000798'),
    'kRenderStateTable': ('0x821E14F0', '0x82E0B478'),
    'kSamplerStateTable': ('0x821E19B0', '0x82E0B938'),
    'kFormatTable': ('0x82003430', '0x82149990'),
    'kFullViewport': ('0x820031D0', '0x821497E4'),
    'kHiZOwnerVa': ('0x821ED330', '0x8300465C'),
    'kGameNoLargePagesVa': ('0x821ED308', '0x83004644'),
    'kDeviceCapsVa': ('0x82003800', '0x82149E48'),
    'kVblankHandler': ('0x820A4C08', '0x828DDB70'),
    'kVblankHandlerWords': ('69', '69'),
    'kVblankHandlerHash': ('0x49BA3A1B1EAA1B6E', '0xBE1E3F741ED93A78'),
}
IMPORTS = [('__imp__sub_8208DA10', '__imp__sub_829F3C70'), ('__imp__sub_82088CE0', '__imp__sub_829F3C40'),
           ('__imp__sub_8225FB78', '__imp__sub_828E63B8')]
CONST = re.compile(r'^(\s*(?:static\s+)?constexpr\s+(?:u8|u16|u32|u64|uint32_t|uint64_t)\s+(\w+)\s*=\s*)'
                   r'(0x[0-9A-Fa-f]+|\d+)((?:u|U|ull|ULL)?\s*;.*)$')


def value_of(text):
    return int(text, 16) if text.lower().startswith('0x') else int(text)


def process(path, problems):
    text = open(path, encoding='utf-8', newline='').read()
    if MARK in text:
        return text, []
    eol = '\r\n' if '\r\n' in text else '\n'
    lines = text.split(eol)
    changes = []
    for i, line in enumerate(lines):
        code, sep, comment = line.partition('//')
        new = code
        m = CONST.match(code)
        if m and m.group(2) in GLOBALS:
            old, want = GLOBALS[m.group(2)]
            if value_of(m.group(3)) == value_of(old):
                new = m.group(1) + want + m.group(4)
            elif value_of(m.group(3)) != value_of(want):
                problems.append('%s:%d: %s = %s, expected Futari\'s %s' % (path, i + 1, m.group(2), m.group(3), old))
        for old, want in IMPORTS:
            new = new.replace(old, want)
        if new != code:
            lines[i] = new + sep + comment
            changes.append((i + 1, line, lines[i]))
    out = eol.join(lines)
    if changes:
        k = out.find('#')
        out = out[:k] + MARK + eol + out[k:] if k >= 0 else MARK + eol + out
    return out, changes


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    problems = []
    total = 0
    seen = set()
    paths = sorted(p for ext in ('*.cpp', '*.h') for p in glob.glob(os.path.join(ENGINE, '**', ext), recursive=True)
                   if os.path.basename(p) not in SKIP_FILES)
    for path in paths:
        out, changes = process(path, problems)
        rel = os.path.relpath(path, ROOT).replace('\\', '/')
        for n, old, new in changes:
            print('%s:%d: %s\n    -> %s' % (rel, n, old.strip(), new.strip()))
            for name in GLOBALS:
                if re.search(r'\b%s\b' % name, old):
                    seen.add(name)
        total += len(changes)
        if changes and a.write:
            open(path, 'w', encoding='utf-8', newline='').write(out)
    print('\n%d lines %s' % (total, 'changed' if a.write else 'would change (dry run; --write applies)'))
    for name in sorted(set(GLOBALS) - seen - {'kVblankHandlerWords'}):
        print('not found (already translated, or gone): %s' % name)
    for p in problems:
        print('CHECK BY HAND: %s' % p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
